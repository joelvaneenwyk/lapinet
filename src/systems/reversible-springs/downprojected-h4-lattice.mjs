export const GOLDEN_RATIO=(1+Math.sqrt(5))/2;
const HOPF_AXIS=Object.freeze((()=>{
 const v=[.313,.481,.829],norm=Math.hypot(...v);
 return v.map(x=>x/norm);
})());
export function projectH4CoefficientSite(coefficients,projection='orthographic'){
 if(!Array.isArray(coefficients)||coefficients.length!==8||
  coefficients.some(x=>!Number.isInteger(x)))throw Error('H4 site requires eight integer coefficients');
 if(!['orthographic','hopf'].includes(projection))throw Error('Unknown H4 projection');
 const q=Array.from({length:4},(_,i)=>
  (coefficients[2*i]+GOLDEN_RATIO*coefficients[2*i+1])/2);
 if(projection==='orthographic')return q.slice(1);
 const [w,x,y,z]=q,rad=Math.hypot(...q);
 if(rad===0)return [0,0,0];
 const [u,v,t]=HOPF_AXIS;
 const cross=[y*t-z*v,z*u-x*t,x*v-y*u];
 const doubleCross=[
  y*cross[2]-z*cross[1],
  z*cross[0]-x*cross[2],
  x*cross[1]-y*cross[0]
 ];
 return HOPF_AXIS.map((a,i)=>
  (rad*rad*a+2*w*cross[i]+2*doubleCross[i])/rad);
}
const key=a=>a.join(',');
const spatialKey=p=>p.map(x=>x.toFixed(6)).join(',');
export function generateProjectedH4Lattice({
 radius=3,projection='orthographic',worldScale=1
}={}){
 if(![2,3,4].includes(radius))throw Error('H4 sample radius must be 2, 3 or 4');
 if(!['orthographic','hopf'].includes(projection))throw Error('Unknown H4 projection');
 if(!(worldScale>0)||!Number.isFinite(worldScale))throw Error('Invalid H4 world scale');
 const nodes=[],coords=new Array(8).fill(0);
 function enumerate(axis,remaining){
  if(axis===8){nodes.push(coords.slice());return;}
  for(let v=-remaining;v<=remaining;v++){
   coords[axis]=v;
   enumerate(axis+1,remaining-Math.abs(v));
  }
 }
 enumerate(0,radius);
 const index=new Map(nodes.map((coords,i)=>[key(coords),i]));
 const points=nodes.map(c=>projectH4CoefficientSite(c,projection));
 const seen=new Set(),vertices=[];
 let collapsed=0,duplicates=0,rootEdges=0;
 // One root from each antipodal pair gives each undirected H4 edge once.
 for(let i=0;i<nodes.length;i++){
  const site=nodes[i],a=points[i];
  for(let r=0;r<H4_ROOT_DELTAS.length;r+=2){
   const step=H4_ROOT_DELTAS[r];
   const j=index.get(key(site.map((x,k)=>x+step[k])));
   if(j===undefined)continue;
   rootEdges++;
   const b=points[j];
   if(a.reduce((sum,x,k)=>sum+(x-b[k])**2,0)<1e-14){collapsed++;continue;}
   const ak=spatialKey(a),bk=spatialKey(b);
   const edgeKey=ak<bk?ak+'|'+bk:bk+'|'+ak;
   if(seen.has(edgeKey)){duplicates++;continue;}
   seen.add(edgeKey);
   vertices.push(...a.map(x=>x*worldScale),1,...b.map(x=>x*worldScale),1);
  }
 }
 return {
  vertices:new Float32Array(vertices),siteCount:nodes.length,
  edgeCount:vertices.length/8,rootEdges,collapsed,duplicates,
  projection,radius,rootAlphabet:H4_ROOT_DELTAS.length,
  distinctProjectedSites:new Set(points.map(spatialKey)).size
 };
}
