test("fixture records retain stable IDs and valid E8 channels", () => {
  const fixture = createScsFixtureData(4096);
  assert.equal(fixture.records.length, 4096 * 4);
  assert.equal(fixture.stableIds.length, 4096);
  assert.equal(new Set(fixture.stableIds).size, 4096);

  for (let i = 0; i < 4096; i += 1) {
    const channel = fixture.records[i * 4 + 3];
    assert.ok(channel < 240);
  }
});
